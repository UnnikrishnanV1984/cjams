CREATE OR REPLACE FUNCTION cjams.sp_ene_outbound_interface_gen_data_35(	vl_client_id integer, 
																		vl_other_id bigint, 
																		vs_transaction_type_cd character varying, 
																		vl_transaction_sequence integer, 
																		vd_transaction_ts timestamp without time zone, 
																		OUT vs_message character varying, 
																		OUT vl_output_sqlcode character varying
																		)
RETURNS record
LANGUAGE plpgsql
AS $function$
------------------------------------------------------------------------
-- SQL Stored Procedure
-- Author: Vineet Tirodkar
-- Date Created: 11/25/2020
-- Description: To generate E&E Inbound data for Record Type 35

-- Revision(s):
------------------------------------------------------------------------
DECLARE VS_RECORD_TYPE VARCHAR(2);
	VL_RECORD_SEQUENCE INTEGER DEFAULT 000;
	VS_TRANSACTION_SEQUENCE VARCHAR(5);
	VS_RECORD_SEQUENCE VARCHAR(3);
	-- Client Variables
	VS_CIS_CLIENT_ID VARCHAR(10); --  ENE_OUT_COL6
	ENE_OUT_RES_COL1 CHAR(3);
	ENE_OUT_RES_COL2 VARCHAR(9); -- INTEGER
	ENE_OUT_RES_COL3 VARCHAR(50);
	ENE_OUT_RES_COL4 CHAR(5);
	ENE_OUT_RES_COL5 CHAR(3);
	ENE_OUT_RES_COL6 CHAR(5);
	ENE_OUT_RES_COL7 VARCHAR(50);
	ENE_OUT_RES_COL8 CHAR(2);
	ENE_OUT_RES_COL9 INTEGER;
	ENE_OUT_RES_COL10 DECIMAL(10,2);
	ENE_OUT_RES_COL10_CONV VARCHAR(15);
	ENE_OUT_RES_COL11 DECIMAL(10,2);
	ENE_OUT_RES_COL11_CONV VARCHAR(15);

DECLARE CURSOR_RES CURSOR FOR
SELECT SUBSTRING(F_PLVALUE(personasset.predirtypekey,69),1,3),
	SUBSTRING(personasset.addressline1,'(^[0-9]+)'), 
	TRIM(substring(personasset.addressline1,'([[:alpha:]\s]+)')), 
	personasset.streetsuffixtypekey,
	SUBSTRING(F_PLVALUE(personasset.postdirtypekey,69),1,3),
	personasset.addressline2,
	personasset.cityname,
	personasset.statetypekey,
	(SUBSTRING(COALESCE(personasset.zip5no::VARCHAR,'00000'),1,5) || SUBSTR(COALESCE(personasset.zip4no::VARCHAR,'0000'),1,4))::INTEGER,
	marketvaluetypekey,
	amountowed
FROM personasset, 
	person 
WHERE personasset.personid = person.personid
	and person.cjamspid = VL_CLIENT_ID
	AND personasset.assettypekey IN ('81', 'RES')
	AND personasset.caresassetno IS NULL
	AND personasset.activeflag = 1;

BEGIN    
	VL_OUTPUT_SQLCODE:='00000';   
	-- RAISE NOTICE 'GEN DATA 35 STARTS';--
	-- SET transaction sequence
	VS_TRANSACTION_SEQUENCE := LTRIM(RTRIM(VL_TRANSACTION_SEQUENCE::VARCHAR)) ;

	-- Get CIS_CLIENT_ID
	BEGIN
		SELECT person.cisclientid
			INTO VS_CIS_CLIENT_ID
		FROM person  	
		WHERE person.cjamspid = VL_CLIENT_ID
			AND person.activeflag  = 1; 

		EXCEPTION WHEN OTHERS THEN 
			VL_OUTPUT_SQLCODE  :=  SQLSTATE;
			VS_MESSAGE :=  '(E&E) SELECT cisclientid FAILED FOR person'  ;
			RETURN;
	END ;

	-- Generate records for record type 35
	VS_RECORD_TYPE := '35';
	VL_RECORD_SEQUENCE := 000 ;
	VS_RECORD_SEQUENCE := '';

    IF  VS_RECORD_TYPE = '35' THEN

       OPEN CURSOR_RES;
       <<CURS_RES>>
       WHILE VL_OUTPUT_SQLCODE = '00000'  LOOP
             FETCH CURSOR_RES INTO ENE_OUT_RES_COL1, ENE_OUT_RES_COL2, ENE_OUT_RES_COL3,
                                   ENE_OUT_RES_COL4, ENE_OUT_RES_COL5, ENE_OUT_RES_COL6,
                                   ENE_OUT_RES_COL7, ENE_OUT_RES_COL8, ENE_OUT_RES_COL9,
                                   ENE_OUT_RES_COL10, ENE_OUT_RES_COL11 ;

            EXIT CURS_RES WHEN NOT FOUND;
	    
	
			VL_RECORD_SEQUENCE := VL_RECORD_SEQUENCE + 1 ;
			VS_RECORD_SEQUENCE := LTRIM(RTRIM(VL_RECORD_SEQUENCE::VARCHAR));	

			ENE_OUT_RES_COL10_CONV := LTRIM(RTRIM(ENE_OUT_RES_COL10::VARCHAR)) ;
			ENE_OUT_RES_COL10_CONV := SUBSTRING('00000000000',1,11 - LENGTH(ENE_OUT_RES_COL10_CONV)) || ENE_OUT_RES_COL10_CONV ;

			ENE_OUT_RES_COL11_CONV := LTRIM(RTRIM(ENE_OUT_RES_COL11::VARCHAR)) ;
			ENE_OUT_RES_COL11_CONV := SUBSTRING('00000000000',1,11 - LENGTH(ENE_OUT_RES_COL11_CONV)) || ENE_OUT_RES_COL11_CONV ;	
	

			-- Set Interface Data
			INSERT INTO eneoutboundinterface
				(	ENE_RECORD_ID,
					STATUS_CD,
					BATCH_SEQ_NO,
					TRANSACTION_SEQ_NO,
					TRANSACTION_TYPE_CD,
					CIS_CLIENT_ID,
					RECORD_TYPE_CD,
					TRANSACTION_TS,
					RECORD_SEQ_NO,
					ENE_OUT_COL1,
					ENE_OUT_COL2,
					ENE_OUT_COL3,
					ENE_OUT_COL4,
					ENE_OUT_COL5,
					ENE_OUT_COL6,
					ENE_OUT_COL7,
					ENE_OUT_COL8,
					ENE_OUT_COL9,
					ENE_OUT_COL10,
					ENE_OUT_COL11
				)
	     SELECT
			NEXTVAL('SQ_ENEOUTBOUNDINTERFACE'),
			'000',
			'',
			(CASE WHEN LENGTH(VS_TRANSACTION_SEQUENCE) = 1 THEN '0000'||VS_TRANSACTION_SEQUENCE
				WHEN LENGTH(VS_TRANSACTION_SEQUENCE) = 2 THEN '000'||VS_TRANSACTION_SEQUENCE
				WHEN LENGTH(VS_TRANSACTION_SEQUENCE) = 3 THEN '00'||VS_TRANSACTION_SEQUENCE
				WHEN LENGTH(VS_TRANSACTION_SEQUENCE) = 4 THEN '0'||VS_TRANSACTION_SEQUENCE
				WHEN LENGTH(VS_TRANSACTION_SEQUENCE) = 5 THEN VS_TRANSACTION_SEQUENCE
			END),
			VS_TRANSACTION_TYPE_CD,
			COALESCE(SUBSTRING('000000000',1,9 - LENGTH(LTRIM(RTRIM(VS_CIS_CLIENT_ID)))) || LTRIM(RTRIM(VS_CIS_CLIENT_ID)),'000000000'),
			'35',
			VD_TRANSACTION_TS,
			(CASE WHEN LENGTH(VS_RECORD_SEQUENCE) = 1 THEN '00'||VS_RECORD_SEQUENCE
				WHEN LENGTH(VS_RECORD_SEQUENCE) = 2 THEN '0'||VS_RECORD_SEQUENCE
				WHEN LENGTH(VS_RECORD_SEQUENCE) = 3 THEN VS_RECORD_SEQUENCE
			END),
			ENE_OUT_RES_COL1,
			ENE_OUT_RES_COL2,
			ENE_OUT_RES_COL3,
			ENE_OUT_RES_COL4,
			ENE_OUT_RES_COL5,
			ENE_OUT_RES_COL6,
			ENE_OUT_RES_COL7,
			ENE_OUT_RES_COL8,
			(CASE WHEN ENE_OUT_RES_COL9 = 0 THEN '000000000'
				WHEN ENE_OUT_RES_COL9 IS NULL THEN '000000000'
				ELSE SUBSTRING('000000000',1,9 - LENGTH(LTRIM(RTRIM(ENE_OUT_RES_COL9::VARCHAR)))) || LTRIM(RTRIM(ENE_OUT_RES_COL9::VARCHAR))
			END), 		
			(CASE WHEN ENE_OUT_RES_COL10_CONV = '' THEN '00000000.00'
				WHEN LENGTH(ENE_OUT_RES_COL10_CONV) <= 0 THEN '00000000.00'
				ELSE COALESCE(ENE_OUT_RES_COL10_CONV::VARCHAR,'00000000.00')
			END),  		
			(CASE WHEN ENE_OUT_RES_COL11_CONV = '' THEN '00000000.00'
				WHEN LENGTH(ENE_OUT_RES_COL11_CONV) <= 0 THEN '00000000.00'
				ELSE COALESCE(ENE_OUT_RES_COL11_CONV::VARCHAR,'00000000.00')
			END)  		
		;
	
		-- RAISE NOTICE 'INSERT IN GEN DATA 35 SUCCESSFUL';--
		END LOOP;
		CLOSE CURSOR_RES;
    END IF;

    EXCEPTION WHEN OTHERS THEN 
		VL_OUTPUT_SQLCODE  :=  SQLSTATE;
		VS_MESSAGE := '(E&E) INSERT INTO eneoutboundinterface FAILED ' || SQLERRM  ;
		RETURN;
    
END 
;
$function$
;
