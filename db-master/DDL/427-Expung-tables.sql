--## ALL CLIENTS PARTICIPATING IN A CASE (CJAMS)
--## TRIGGER POINT WHEN EVER A CLIENT IS ADDED TO A CASE
DROP TABLE IF EXISTS tb_cjams_client_participation;
CREATE TABLE cjams.tb_cjams_client_participation
(CJAMS_CLIENT_PARTICIPATION_ID		SERIAL,
 CJAMS_PERSON_ID					INTEGER,
 CHESSIE_CLIENT_ID					INTEGER,
 CIS_CLIENT_ID						VARCHAR(10),
 ACTION_FLAG						CHAR(1),
 PARTICIPATION_SW					CHAR(1),
 CREATE_TS							TIMESTAMP,
 CREATE_USER_ID						VARCHAR(10),
 UPDATE_TS							TIMESTAMP,
 UPDATE_USER_ID						VARCHAR(10),
 DELETE_SW							CHAR(1)
);
 
