/*

Create table mdm_sys_reference.
This table is used by MDM team to perform
bulk data load on the CJAMS person data.

They will create the MDM IDs and IRNs for the CJAMS ID shared and
update this table back with the generated MDM / IRNs. 


*/

drop TABLE if exists cjams.mdm_sys_reference;

CREATE TABLE if not exists  cjams.mdm_sys_reference
(
    mdm_ref_id uuid DEFAULT cjams.gen_random_uuid() NOT NULL,
	mdm_id character varying(50)  NULL,
    irn_id character varying(50)  NULL,
    source_sys character varying(25)  NULL,
    source_sys_id character varying(50)  NULL,
    active_flag character(1) DEFAULT 'Y'::bpchar,
    process_status character varying(25),
    insert_date timestamp(6) without time zone NOT NULL DEFAULT now(),
    update_date timestamp(6) without time zone NOT NULL DEFAULT now(),
    CONSTRAINT pk_mdmssyreference PRIMARY KEY (mdm_ref_id)
);

COMMENT ON COLUMN mdm_sys_reference.mdm_ref_id IS 'Unique internal surrogate key generated via UUID for global record tracking.';
COMMENT ON COLUMN mdm_sys_reference.mdm_id IS 'The primary Master Data identifier assigned to this specific entity.';
COMMENT ON COLUMN mdm_sys_reference.irn_id IS 'IRN / CIS ID number generated by MDM.';
COMMENT ON COLUMN mdm_sys_reference.source_sys IS 'The name of the originating system.';
COMMENT ON COLUMN mdm_sys_reference.source_sys_id IS 'The original unique identifier from the source system.';
COMMENT ON COLUMN mdm_sys_reference.active_flag IS 'Soft-delete indicator: Y = Active, N = Inactive.';
COMMENT ON COLUMN mdm_sys_reference.process_status IS 'Tracks the ETL/processing stage (e.g., PENDING, COMPLETED, ERROR).';
COMMENT ON COLUMN mdm_sys_reference.insert_date IS 'Audit timestamp for when the record was first created.';
COMMENT ON COLUMN mdm_sys_reference.update_date IS 'Audit timestamp for the most recent modification to this record.';


