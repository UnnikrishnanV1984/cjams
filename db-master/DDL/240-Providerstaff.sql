DROP TABLE if exists cjams.providerstaff;

CREATE TABLE if not exists cjams.providerstaff (
	provider_staff_id uuid NOT NULL DEFAULT gen_random_uuid(),
	object_id varchar(50) NULL,
	first_nm varchar(150) NULL,
	middle_nm varchar(50) NULL,
	last_nm varchar(150) NULL,
	affiliation_type varchar(100) NULL,
	job_title varchar(100) NULL,
	employee_type varchar(100) NULL,
	start_date timestamp NULL,
	end_date timestamp NULL,
	reason_for_leaving varchar(50) NULL,
	behavioral_interventions_training varchar(50) NULL,
	cps_clearance_request_date timestamp NULL,
	cps_clearance_result_date timestamp NULL,
	cps_rcc_compliant varchar(50) NULL,
	cps_cpa_compliant varchar(50) NULL,
	federal_clearance_request_date timestamp NULL,
	federal_clearance_result_date timestamp NULL,
	federal_rcc_compliant varchar(50) NULL,
	federal_cpa_compliant varchar(50) NULL,
	state_clearance_request_date timestamp NULL,
	state_clearance_result_date timestamp NULL,
	state_rcc_compliant varchar(50) NULL,
	state_cpa_compliant varchar(50) NULL,
	rcc_certificate_type varchar(100) NULL,
	rcc_certificate_due_date timestamp NULL,
	rcc_date_application_mailed timestamp NULL,
	rcc_date_tested timestamp NULL,
	rcc_certification_effective_date timestamp NULL,
	staff_comment varchar(500) NULL,
	rcc_certification_number varchar(50) NULL,
	rcc_certification_renewal_date timestamp NULL,
	create_ts varchar(30) NULL,
	create_user_id varchar(50) NULL,
	update_ts varchar(30) NULL,
	update_user_id varchar(50) NULL,
	delete_sw bpchar(1) NULL DEFAULT 'N'::bpchar
);
